// Generates supabase/migrations/20261019000003_seed_reference_data.sql from
// data/seed.json so the database and the offline fallback share one source.
//   node scripts/generate-seed-sql.mjs          write the file
//   node scripts/generate-seed-sql.mjs --check  fail if the file is stale
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const seed = JSON.parse(readFileSync(join(root, 'data/seed.json'), 'utf8'));
const out = join(root, 'supabase/migrations/20261019000003_seed_reference_data.sql');

const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replaceAll("'", "''")}'`);
const arr = (a) => (a.length ? `array[${a.map(q).join(', ')}]::text[]` : `'{}'::text[]`);
const bool = (b) => (b ? 'true' : 'false');

const lines = [
  '-- GENERATED by scripts/generate-seed-sql.mjs from data/seed.json — do not edit by hand.',
  '-- Initial sections, staff roster, settings, quotes, a starter poll and a welcome article.',
  '-- Everything uses "on conflict do nothing", so re-running never overwrites later edits.',
  '',
];

for (const s of seed.sections) {
  lines.push(
    `insert into public.sections (id, name, description, icon, subsections, sort_order, active) values (${[
      q(s.id), q(s.name), q(s.description), q(s.icon), arr(s.subsections), s.sort_order, bool(s.active ?? true),
    ].join(', ')}) on conflict (id) do nothing;`,
  );
}
lines.push('');
for (const [key, value] of Object.entries(seed.settings)) {
  lines.push(`insert into public.site_settings (key, value) values (${q(key)}, ${q(JSON.stringify(value))}::jsonb) on conflict (key) do nothing;`);
}
lines.push('');
for (const quote of seed.quotes) {
  lines.push(`insert into public.quotes (text, attribution, sort_order) select ${q(quote.text)}, ${q(quote.attribution)}, ${quote.sort_order} where not exists (select 1 from public.quotes where text = ${q(quote.text)});`);
}
lines.push('');
for (const p of seed.staff) {
  lines.push(
    `insert into public.staff_members (slug, name, title, sections, lead_of, bio, sort_order) values (${[
      q(p.slug), q(p.name), q(p.title), arr(p.sections), arr(p.lead_of), q(p.bio), p.sort_order,
    ].join(', ')}) on conflict (slug) do nothing;`,
  );
}
lines.push('');
for (const poll of seed.polls) {
  lines.push(`insert into public.polls (category, question, options) select ${q(poll.category)}, ${q(poll.question)}, ${q(JSON.stringify(poll.options))}::jsonb where not exists (select 1 from public.polls where question = ${q(poll.question)});`);
}
lines.push('');
for (const a of seed.articles) {
  lines.push(
    `insert into public.articles (slug, title, deck, body_md, section_id, subsection, status, is_lead, published_at, tags) values (${[
      q(a.slug), q(a.title), q(a.deck), q(a.body_md), q(a.section_id), q(a.subsection), q(a.status), bool(a.is_lead), q(a.published_at), arr(a.tags),
    ].join(', ')}) on conflict (slug) do nothing;`,
  );
}
lines.push('');

const sql = lines.join('\n');
if (process.argv.includes('--check')) {
  let current = '';
  try { current = readFileSync(out, 'utf8'); } catch { /* missing */ }
  if (current !== sql) {
    console.error('Seed migration is out of date. Run: node scripts/generate-seed-sql.mjs');
    process.exit(1);
  }
} else {
  writeFileSync(out, sql);
  console.log(`Wrote ${out}`);
}
